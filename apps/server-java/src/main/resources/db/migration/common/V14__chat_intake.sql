-- 对话式需求录入（C1）：会话、消息、草稿（按工作区隔离）。工具结果只存摘要与哈希，不存整份仓库文件。
CREATE TABLE chat_session (
  id VARCHAR(40) PRIMARY KEY,
  workspace_id VARCHAR(40) NOT NULL,
  created_by VARCHAR(200) NOT NULL,
  title VARCHAR(200),
  status VARCHAR(20) NOT NULL,
  project_id VARCHAR(64),
  task_id VARCHAR(64),
  draft_version INTEGER NOT NULL DEFAULT 0,
  usd_spent DOUBLE PRECISION NOT NULL DEFAULT 0,
  tokens BIGINT NOT NULL DEFAULT 0,
  turns INTEGER NOT NULL DEFAULT 0,
  file_reads INTEGER NOT NULL DEFAULT 0,
  created_at VARCHAR(40) NOT NULL,
  updated_at VARCHAR(40) NOT NULL
);
CREATE INDEX ix_chat_ws ON chat_session(workspace_id, updated_at);
CREATE TABLE chat_message (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id VARCHAR(40) NOT NULL,
  workspace_id VARCHAR(40) NOT NULL,
  role VARCHAR(20) NOT NULL,
  content TEXT,
  tool_name VARCHAR(60),
  tool_summary TEXT,
  tool_hash VARCHAR(64),
  model VARCHAR(100),
  tokens BIGINT,
  usd DOUBLE PRECISION,
  created_at VARCHAR(40) NOT NULL
);
CREATE INDEX ix_chat_msg ON chat_message(session_id, id);
CREATE TABLE chat_draft (
  session_id VARCHAR(40) NOT NULL,
  version INTEGER NOT NULL,
  workspace_id VARCHAR(40) NOT NULL,
  body TEXT NOT NULL,
  edited_by VARCHAR(20) NOT NULL,
  created_at VARCHAR(40) NOT NULL,
  PRIMARY KEY (session_id, version)
);
