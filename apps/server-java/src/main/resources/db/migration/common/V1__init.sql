CREATE TABLE product_line (
  id VARCHAR(100) PRIMARY KEY, name VARCHAR(200) NOT NULL,
  autonomy_level VARCHAR(10) NOT NULL DEFAULT 'L1',
  config TEXT NOT NULL DEFAULT '{}',
  paused INTEGER NOT NULL DEFAULT 0,
  intake_paused_until VARCHAR(40),
  last_tightened_at VARCHAR(40),
  created_at VARCHAR(40) NOT NULL
);
CREATE TABLE signal (
  id VARCHAR(64) PRIMARY KEY, product_line VARCHAR(100) NOT NULL, source VARCHAR(50) NOT NULL, source_ref VARCHAR(200), content TEXT,
  fingerprint VARCHAR(64) NOT NULL, task_id VARCHAR(64), created_at VARCHAR(40) NOT NULL,
  CONSTRAINT uq_signal_fp UNIQUE (product_line, fingerprint)
);
CREATE INDEX ix_signal_ref ON signal(product_line, source_ref);
CREATE TABLE task (
  id VARCHAR(64) PRIMARY KEY, product_line VARCHAR(100) NOT NULL, title VARCHAR(500) NOT NULL, problem TEXT DEFAULT '',
  priority_score DOUBLE PRECISION NOT NULL DEFAULT 0, risk_level VARCHAR(20) NOT NULL DEFAULT 'low',
  status VARCHAR(20) NOT NULL, path TEXT NOT NULL DEFAULT '[]',
  scope_level INTEGER NOT NULL DEFAULT 0, strategy_variant INTEGER NOT NULL DEFAULT 0,
  current_iteration INTEGER NOT NULL DEFAULT 1,
  loop_count INTEGER NOT NULL DEFAULT 0, reject_count INTEGER NOT NULL DEFAULT 0,
  review_retry INTEGER NOT NULL DEFAULT 0, rollback_count INTEGER NOT NULL DEFAULT 0,
  requeue_count INTEGER NOT NULL DEFAULT 0, degrade_count INTEGER NOT NULL DEFAULT 0,
  heal_count INTEGER NOT NULL DEFAULT 0, step_attempts INTEGER NOT NULL DEFAULT 0,
  cooldown_until VARCHAR(40), parent_task_id VARCHAR(64), discard_reason VARCHAR(50), discard_detail TEXT,
  budget_tokens BIGINT NOT NULL, spent_tokens BIGINT NOT NULL DEFAULT 0,
  budget_usd DOUBLE PRECISION NOT NULL, spent_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
  budget_ci DOUBLE PRECISION NOT NULL DEFAULT 0, spent_ci DOUBLE PRECISION NOT NULL DEFAULT 0,
  budget_iterations INTEGER NOT NULL DEFAULT 50, spent_iterations INTEGER NOT NULL DEFAULT 0,
  plan TEXT, context TEXT NOT NULL DEFAULT '{}', release TEXT NOT NULL DEFAULT '{}',
  paused INTEGER NOT NULL DEFAULT 0, anomaly_from VARCHAR(20),
  observe_until VARCHAR(40), feedback_done INTEGER NOT NULL DEFAULT 0, accepted_once INTEGER NOT NULL DEFAULT 0,
  workflow_id VARCHAR(100) UNIQUE, next_run_at VARCHAR(40),
  created_at VARCHAR(40) NOT NULL, status_changed_at VARCHAR(40) NOT NULL, released_at VARCHAR(40),
  version INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX ix_task_status ON task(status);
CREATE INDEX ix_task_line ON task(product_line);
CREATE TABLE iteration (
  id VARCHAR(64) PRIMARY KEY, task_id VARCHAR(64) NOT NULL, seq INTEGER NOT NULL, trigger_kind VARCHAR(50) NOT NULL,
  started_at VARCHAR(40) NOT NULL, ended_at VARCHAR(40), outcome VARCHAR(50), CONSTRAINT uq_iter UNIQUE (task_id, seq)
);
CREATE TABLE verdict (
  id VARCHAR(64) PRIMARY KEY, task_id VARCHAR(64) NOT NULL, iteration_seq INTEGER, gate VARCHAR(50) NOT NULL,
  rule_results TEXT, votes TEXT, aggregate_score DOUBLE PRECISION, decision VARCHAR(30) NOT NULL, evidence_ids TEXT,
  created_at VARCHAR(40) NOT NULL
);
CREATE INDEX ix_verdict_task ON verdict(task_id);
CREATE TABLE task_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, task_id VARCHAR(64), iteration_seq INTEGER,
  event_type VARCHAR(50) NOT NULL, from_status VARCHAR(20), to_status VARCHAR(20), edge VARCHAR(30),
  actor VARCHAR(100) NOT NULL, model VARCHAR(100), prompt_version VARCHAR(50), payload TEXT,
  idempotency_key VARCHAR(300) UNIQUE, prev_hash VARCHAR(64) NOT NULL, hash VARCHAR(64) NOT NULL, occurred_at VARCHAR(40) NOT NULL
);
CREATE INDEX ix_event_task ON task_event(task_id, id);
CREATE INDEX ix_event_time ON task_event(occurred_at);
CREATE TABLE evidence (
  id VARCHAR(64) PRIMARY KEY, task_id VARCHAR(64) NOT NULL, iteration_seq INTEGER, stage VARCHAR(30) NOT NULL, kind VARCHAR(50) NOT NULL,
  uri VARCHAR(300) NOT NULL, sha256 VARCHAR(64) NOT NULL, content TEXT NOT NULL, produced_by VARCHAR(100), model VARCHAR(100), created_at VARCHAR(40) NOT NULL
);
CREATE INDEX ix_evidence_task ON evidence(task_id);
CREATE TABLE anomaly (
  id VARCHAR(64) PRIMARY KEY, task_id VARCHAR(64) NOT NULL, stage VARCHAR(30), type VARCHAR(50) NOT NULL, severity VARCHAR(20), status VARCHAR(20) NOT NULL,
  heal_steps TEXT NOT NULL DEFAULT '[]', resolution VARCHAR(50), opened_at VARCHAR(40) NOT NULL, resolved_at VARCHAR(40)
);
CREATE TABLE budget_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, task_id VARCHAR(64), product_line VARCHAR(100), agent VARCHAR(100), model VARCHAR(100),
  tokens BIGINT NOT NULL DEFAULT 0, usd DOUBLE PRECISION NOT NULL DEFAULT 0, ci_minutes DOUBLE PRECISION NOT NULL DEFAULT 0,
  ledger_key VARCHAR(300) UNIQUE, day VARCHAR(10) NOT NULL, occurred_at VARCHAR(40) NOT NULL
);
CREATE INDEX ix_ledger_day ON budget_ledger(day);
CREATE TABLE kill_switch (
  id VARCHAR(64) PRIMARY KEY, scope VARCHAR(100) NOT NULL, mode VARCHAR(30) NOT NULL, source VARCHAR(20) NOT NULL, reason TEXT,
  trigger_key VARCHAR(100), active INTEGER NOT NULL DEFAULT 1, created_at VARCHAR(40) NOT NULL, released_at VARCHAR(40)
);
CREATE TABLE settings (skey VARCHAR(100) PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE tool_ops (op_key VARCHAR(300) PRIMARY KEY, result TEXT NOT NULL, created_at VARCHAR(40) NOT NULL);
CREATE TABLE adapter_call (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at VARCHAR(40) NOT NULL, adapter VARCHAR(20) NOT NULL, op VARCHAR(80) NOT NULL, method VARCHAR(10), path VARCHAR(500),
  status INTEGER, ok INTEGER NOT NULL DEFAULT 1, dry_run INTEGER NOT NULL DEFAULT 0, duration_ms BIGINT NOT NULL DEFAULT 0,
  op_key VARCHAR(300), line VARCHAR(100), note VARCHAR(600)
);
CREATE TABLE audit_anchor (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, head_hash VARCHAR(64) NOT NULL, event_id BIGINT NOT NULL, anchored_at VARCHAR(40) NOT NULL);
