-- Schema 3 is opt-in. Existing v1/v2 tasks and evidence are not rewritten.
ALTER TABLE task ALTER COLUMN execution_state SET DATA TYPE VARCHAR(40);
ALTER TABLE task ADD COLUMN active_plan_revision_id VARCHAR(80);
ALTER TABLE task ADD COLUMN workflow_block_code VARCHAR(64);
ALTER TABLE task ADD COLUMN workflow_block_reason TEXT;
ALTER TABLE task ADD CONSTRAINT ux_task_scope UNIQUE(workspace_id,project_id,id);
ALTER TABLE task ADD CONSTRAINT ux_task_workspace UNIQUE(workspace_id,id);
CREATE TABLE workflow_plan_revision (
 id VARCHAR(80) PRIMARY KEY, workspace_id VARCHAR(40) NOT NULL, project_id VARCHAR(80) NOT NULL, task_id VARCHAR(80) NOT NULL,
 revision_no INTEGER NOT NULL, parent_revision_id VARCHAR(80), plan_hash VARCHAR(64) NOT NULL, body TEXT NOT NULL,
 status VARCHAR(24) NOT NULL, state_version INTEGER NOT NULL DEFAULT 0, created_at VARCHAR(40) NOT NULL,
 UNIQUE(workspace_id,task_id,revision_no), UNIQUE(workspace_id,project_id,task_id,id), UNIQUE(workspace_id,task_id,id),
 FOREIGN KEY(workspace_id,project_id,task_id) REFERENCES task(workspace_id,project_id,id)
);
CREATE TABLE node_instance (
 id VARCHAR(80) NOT NULL, plan_revision_id VARCHAR(80) NOT NULL, workspace_id VARCHAR(40) NOT NULL, project_id VARCHAR(80) NOT NULL, task_id VARCHAR(80) NOT NULL,
 definition_ref VARCHAR(120) NOT NULL, body TEXT NOT NULL, state VARCHAR(32) NOT NULL DEFAULT 'PENDING',
 PRIMARY KEY(plan_revision_id,id), UNIQUE(workspace_id,project_id,task_id,plan_revision_id,id), UNIQUE(workspace_id,plan_revision_id,id),
 FOREIGN KEY(workspace_id,project_id,task_id,plan_revision_id) REFERENCES workflow_plan_revision(workspace_id,project_id,task_id,id)
);
CREATE TABLE input_binding (
 id VARCHAR(100) NOT NULL, plan_revision_id VARCHAR(80) NOT NULL, node_id VARCHAR(80) NOT NULL,
 workspace_id VARCHAR(40) NOT NULL, project_id VARCHAR(80) NOT NULL, task_id VARCHAR(80) NOT NULL,
 port_name VARCHAR(80) NOT NULL, ordinal INTEGER NOT NULL, version_id VARCHAR(80), producer_node VARCHAR(80), output_port VARCHAR(80), resolved_version_id VARCHAR(80),
 PRIMARY KEY(plan_revision_id,node_id,id), UNIQUE(plan_revision_id,node_id,port_name,ordinal),
 CHECK ((version_id IS NOT NULL AND producer_node IS NULL AND output_port IS NULL) OR (version_id IS NULL AND producer_node IS NOT NULL AND output_port IS NOT NULL)),
 FOREIGN KEY(workspace_id,project_id,task_id,plan_revision_id,node_id) REFERENCES node_instance(workspace_id,project_id,task_id,plan_revision_id,id)
);
CREATE TABLE control_dependency (
 plan_revision_id VARCHAR(80) NOT NULL, from_node VARCHAR(80) NOT NULL, to_node VARCHAR(80) NOT NULL, workspace_id VARCHAR(40) NOT NULL,
 PRIMARY KEY(plan_revision_id,from_node,to_node),
 FOREIGN KEY(workspace_id,plan_revision_id,from_node) REFERENCES node_instance(workspace_id,plan_revision_id,id), FOREIGN KEY(workspace_id,plan_revision_id,to_node) REFERENCES node_instance(workspace_id,plan_revision_id,id)
);
CREATE TABLE artifact_version (
 id VARCHAR(80) PRIMARY KEY, workspace_id VARCHAR(40) NOT NULL, project_id VARCHAR(80) NOT NULL, task_id VARCHAR(80) NOT NULL,
 artifact_type VARCHAR(80) NOT NULL, schema_version INTEGER NOT NULL, content_digest VARCHAR(64) NOT NULL,
 producer_node VARCHAR(80), producer_run VARCHAR(80), output_port VARCHAR(80), plan_revision_id VARCHAR(80), body TEXT NOT NULL, created_at VARCHAR(40) NOT NULL,
 UNIQUE(workspace_id,project_id,id), UNIQUE(workspace_id,id), FOREIGN KEY(workspace_id,project_id,task_id) REFERENCES task(workspace_id,project_id,id)
);
CREATE TABLE artifact_lineage (
 workspace_id VARCHAR(40) NOT NULL, project_id VARCHAR(80) NOT NULL, output_version_id VARCHAR(80) NOT NULL, input_version_id VARCHAR(80) NOT NULL,
 PRIMARY KEY(output_version_id,input_version_id),
 FOREIGN KEY(workspace_id,project_id,output_version_id) REFERENCES artifact_version(workspace_id,project_id,id),
 FOREIGN KEY(workspace_id,project_id,input_version_id) REFERENCES artifact_version(workspace_id,project_id,id)
);
CREATE TABLE artifact_validation (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
 id VARCHAR(80) PRIMARY KEY, workspace_id VARCHAR(40) NOT NULL, version_id VARCHAR(80) NOT NULL,
 profile VARCHAR(80) NOT NULL, result VARCHAR(16) NOT NULL, checked_digest VARCHAR(64) NOT NULL, body TEXT NOT NULL, created_at VARCHAR(40) NOT NULL,
 FOREIGN KEY(workspace_id,version_id) REFERENCES artifact_version(workspace_id,id)
);
CREATE TABLE approval_record (
 id VARCHAR(80) PRIMARY KEY, workspace_id VARCHAR(40) NOT NULL, task_id VARCHAR(80) NOT NULL,
 subject_digest VARCHAR(64) NOT NULL, decision VARCHAR(16) NOT NULL, approver VARCHAR(120) NOT NULL, expires_at VARCHAR(40) NOT NULL, revoked_at VARCHAR(40), created_at VARCHAR(40) NOT NULL, FOREIGN KEY(workspace_id,task_id) REFERENCES task(workspace_id,id)
);
CREATE TABLE artifact_invalidation (
 id VARCHAR(80) PRIMARY KEY, workspace_id VARCHAR(40) NOT NULL, task_id VARCHAR(80) NOT NULL,
 plan_revision_id VARCHAR(80) NOT NULL, consumer_node VARCHAR(80) NOT NULL, reason TEXT NOT NULL, created_at VARCHAR(40) NOT NULL,
 UNIQUE(plan_revision_id,consumer_node),
 FOREIGN KEY(workspace_id,task_id,plan_revision_id) REFERENCES workflow_plan_revision(workspace_id,task_id,id)
);
CREATE TABLE node_run (
 id VARCHAR(80) PRIMARY KEY, workspace_id VARCHAR(40) NOT NULL, project_id VARCHAR(80) NOT NULL, task_id VARCHAR(80) NOT NULL,
 plan_revision_id VARCHAR(80) NOT NULL, node_id VARCHAR(80) NOT NULL, attempt_no INTEGER NOT NULL, input_fingerprint VARCHAR(64) NOT NULL,
 inputs TEXT NOT NULL, role_snapshot TEXT NOT NULL, state VARCHAR(32) NOT NULL, owner_id VARCHAR(80) NOT NULL, epoch BIGINT NOT NULL,
 checkpoint TEXT, started_at VARCHAR(40) NOT NULL, heartbeat_at VARCHAR(40) NOT NULL, ended_at VARCHAR(40), state_version INTEGER NOT NULL DEFAULT 0,
 UNIQUE(plan_revision_id,node_id,attempt_no),
 FOREIGN KEY(workspace_id,project_id,task_id,plan_revision_id,node_id) REFERENCES node_instance(workspace_id,project_id,task_id,plan_revision_id,id)
);
CREATE INDEX ix_node_run_task ON node_run(workspace_id,task_id,state);
CREATE TABLE execution_lease (
 workspace_id VARCHAR(40) NOT NULL, resource_type VARCHAR(32) NOT NULL, resource_id VARCHAR(120) NOT NULL,
 owner_id VARCHAR(80) NOT NULL, epoch BIGINT NOT NULL, expires_at VARCHAR(40) NOT NULL, heartbeat_at VARCHAR(40) NOT NULL,
 PRIMARY KEY(workspace_id,resource_type,resource_id)
);
